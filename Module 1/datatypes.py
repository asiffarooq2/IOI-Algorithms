# String
name = "Asif"

# Integer
age = 28

# Float
height = 5.9

# Boolean
is_student = False

# Print the values
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is Student:", is_student)

# Print the data types
print("\nData Types:")
print("name ->", type(name))
print("age ->", type(age))
print("height ->", type(height))
print("is_student ->", type(is_student))
