# M1 Activity: Swap Two Numbers
# ==========================================

# Assign values
a = 10
b = 20

print("Before Swapping:")
print("a =", a)
print("b =", b)

# Swap using a temporary variable
temp = a
a = b
b = temp

print("\nAfter Swapping:")
print("a =", a)
print("b =", b)
